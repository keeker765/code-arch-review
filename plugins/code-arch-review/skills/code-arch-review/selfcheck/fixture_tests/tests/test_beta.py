"""阳性样本:import 了兄弟测试模块,但**有**可收集的用例。

与 `test_alpha.py` 对着看 —— 那个文件证明「零用例」报得出来,这个证明「有用例时
那条不报」。只测一边的话,一条永不触发的规则也能通过自检。
"""

# 从另一个测试模块导入共享工具:这是 `test-import-test` 要抓的形态。
# 直接写模块名(而不是 `from tests.test_alpha import`)是刻意的 —— 两种写法都要能认出,
# 而这条路径的顶层名才是模块主干名,是判据里最容易写错的一支。
from test_alpha import helper


def test_helper_is_identity():
    """这个函数以 `test` 开头,会被 pytest 收集,于是「零用例」那条不该报。

    断言写在这里而不是委托给别的函数:委托出去会让这个文件看起来没有断言,
    而自检夹具本身不该再引入别的争议。
    """
    # 恒等函数传什么就该回什么 —— 一个断言够了,这里测的是分类不是被测逻辑
    assert helper(1) == 1
